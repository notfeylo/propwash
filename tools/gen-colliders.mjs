// tools/gen-colliders.mjs — `node tools/gen-colliders.mjs`
// Measures the drone's collision shapes from public/models/drone.glb (Phase 2 PRD §5) and writes
// src/config/airframes/colliders.ts: hull support points of frame + stack + battery, the payload
// canister as a capsule, and a contact point under each motor. Run after `pnpm assets`.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';
import { writeFileSync } from 'node:fs';

await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
const doc = await io.read('public/models/drone.glb');

function points(name) {
  const out = [];
  for (const n of doc.getRoot().listNodes()) {
    if (n.getName() !== name || !n.getMesh()) continue;
    const W = n.getWorldMatrix();
    for (const p of n.getMesh().listPrimitives()) {
      const a = p.getAttribute('POSITION');
      const v = [0, 0, 0];
      for (let i = 0; i < a.getCount(); i++) {
        a.getElement(i, v);
        out.push([0, 1, 2].map((r) => W[r] * v[0] + W[4 + r] * v[1] + W[8 + r] * v[2] + W[12 + r]));
      }
    }
  }
  return out;
}

// Frame + stack + battery: body vertices above the canister's mounting straps (those hide with the
// payload; the bottom plate is at y ≈ 0.052).
const body = points('body').filter((p) => p[1] >= 0.045);
// Support points in 98 directions (a fibonacci sphere): the hull's extreme vertices.
const dirs = Array.from({ length: 98 }, (_, i) => {
  const y = 1 - (2 * (i + 0.5)) / 98;
  const r = Math.sqrt(1 - y * y);
  const th = i * Math.PI * (3 - Math.sqrt(5));
  return [Math.cos(th) * r, y, Math.sin(th) * r];
});
const hull = new Map();
for (const d of dirs) {
  let best = null;
  let bestDot = -Infinity;
  for (const p of body) {
    const s = p[0] * d[0] + p[1] * d[1] + p[2] * d[2];
    if (s > bestDot) [best, bestDot] = [p, s];
  }
  hull.set(
    best.map((x) => x.toFixed(4)).join(','),
    best.map((x) => +x.toFixed(4)),
  );
}

// Payload canister → capsule along its longest horizontal axis.
const pay = points('payload');
const mn = [0, 1, 2].map((k) => Math.min(...pay.map((p) => p[k])));
const mx = [0, 1, 2].map((k) => Math.max(...pay.map((p) => p[k])));
const ext = mx.map((v, k) => v - mn[k]);
const axis = ext[0] > ext[2] ? 'x' : 'z';
const radius = Math.min(ext[1], axis === 'x' ? ext[2] : ext[0]) / 2;
const length = axis === 'x' ? ext[0] : ext[2];
const center = mn.map((v, k) => +((v + mx[k]) / 2).toFixed(4));

// Motor contact points: the lowest body vertex within 18 mm of each motor axis.
const MOTORS = [
  [0.1217, 0.1233],
  [0.1217, -0.1233],
  [-0.1217, 0.1233],
  [-0.1217, -0.1233],
];
const allBody = points('body');
const feet = MOTORS.map(([x, z]) => {
  const near = allBody.filter((p) => Math.hypot(p[0] - x, p[2] - z) < 0.018);
  return [x, +Math.min(...near.map((p) => p[1])).toFixed(4), z];
});

const out = `// Generated by tools/gen-colliders.mjs from public/models/drone.glb: do not edit by hand.
// Drone collision shapes (Phase 2 PRD §5), model frame (m).

/** Support points of frame + stack + battery; Rapier builds their convex hull. */
export const HULL_POINTS: readonly (readonly [number, number, number])[] = ${JSON.stringify([...hull.values()])};

/** The payload canister as a capsule (axis ${axis}). */
export const PAYLOAD_CAPSULE = { center: ${JSON.stringify(center)} as const, axis: '${axis}' as const, radius: ${radius.toFixed(4)}, halfLength: ${(length / 2 - radius).toFixed(4)} };

/** Lowest point under each motor (M1..M4): the drone lands on these. */
export const MOTOR_FEET: readonly (readonly [number, number, number])[] = ${JSON.stringify(feet)};
`;
writeFileSync('src/config/airframes/colliders.ts', out);
console.log(
  `hull ${hull.size} points, capsule r ${radius.toFixed(4)} len ${length.toFixed(4)} axis ${axis} at ${center}, feet ${JSON.stringify(feet)}`,
);
